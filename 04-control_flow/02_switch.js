const month = 3

switch (month) {
    case 1:
        console.log("january");
        break;
    case 2:
        console.log("february");
        break;
    case 3:
        console.log("march");
        break;
        

    default:
        console.log("default case");
        
        break;
}


const week = "wednesday";

switch (week) {
    case "sunday":
        console.log("sunday");
        break;
    case "monday":
        console.log("monday");
        break;
    case "tuesday":
        console.log("tuesday");
        break;
    case "wednesday":
        console.log("wednesday");
        break;

    default:
        console.log("default value");
        
        break;
}